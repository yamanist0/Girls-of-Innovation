// generates square gallery thumbnails from the full size photos in assets/girls
// and writes the manifest consumed by components/sections/gallery.tsx
// runs automatically through the prebuild npm script

import crypto from 'node:crypto'
import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const sourceDir = path.join(root, 'assets', 'girls')
const outputDir = path.join(root, 'public', 'gallery')
const manifestPath = path.join(root, 'data', 'gallery.ts')

// the widest a grid cell can get is around 280px (max-w-6xl, 4 columns, 12px gaps)
// so 320 covers 1x screens and 640 covers 2x screens
const variants = [
  { width: 320, quality: 72 },
  { width: 640, quality: 58 }
]

// bump this when the encoding parameters change so cached files are rebuilt
const recipe = 'v1'

const sourceExtensions = new Set(['.webp', '.jpg', '.jpeg', '.png'])

function slugify(name) {
  return name.replace(/[^a-zA-Z0-9]+/g, '-').replace(/^-+|-+$/g, '')
}

async function collectSources() {
  const entries = await fs.readdir(sourceDir, { withFileTypes: true })
  return entries
    .filter(entry => entry.isFile() && sourceExtensions.has(path.extname(entry.name).toLowerCase()))
    .map(entry => entry.name)
    .sort((a, b) => a.localeCompare(b, 'en'))
}

async function exists(target) {
  try {
    await fs.access(target)
    return true
  } catch {
    return false
  }
}

async function buildVariant(sourcePath, targetPath, width, quality) {
  if (await exists(targetPath)) return false

  await sharp(sourcePath)
    .resize(width, width, { fit: 'cover', position: 'attention' })
    .webp({ quality, effort: 5 })
    .toFile(targetPath)

  return true
}

async function pruneStaleFiles(keep) {
  const entries = await fs.readdir(outputDir, { withFileTypes: true })
  const removed = []

  for (const entry of entries) {
    if (!entry.isFile() || keep.has(entry.name)) continue
    await fs.unlink(path.join(outputDir, entry.name))
    removed.push(entry.name)
  }

  return removed
}

function renderManifest(photos) {
  const body = photos
    .map(photo => {
      const srcSet = photo.variants.map(variant => `/gallery/${variant.file} ${variant.width}w`).join(', ')
      const fallback = photo.variants[0]
      return [
        '  {',
        `    src: '/gallery/${fallback.file}',`,
        `    srcSet: '${srcSet}',`,
        `    width: ${fallback.width},`,
        `    height: ${fallback.width}`,
        '  }'
      ].join('\n')
    })
    .join(',\n')

  return [
    '// generated by scripts/generate-gallery-thumbs.mjs',
    '// do not edit by hand, add or remove photos in assets/girls instead',
    '',
    'export interface GalleryPhoto {',
    '  src: string',
    '  srcSet: string',
    '  width: number',
    '  height: number',
    '}',
    '',
    'export const galleryPhotos: GalleryPhoto[] = [',
    body,
    ']',
    ''
  ].join('\n')
}

async function main() {
  await fs.mkdir(outputDir, { recursive: true })

  const sources = await collectSources()

  if (sources.length === 0) {
    throw new Error(`no source photos found in ${path.relative(root, sourceDir)}`)
  }

  const photos = []
  const keep = new Set()
  let generated = 0

  for (const name of sources) {
    const sourcePath = path.join(sourceDir, name)
    const buffer = await fs.readFile(sourcePath)
    const slug = slugify(path.basename(name, path.extname(name)))
    const built = []

    for (const variant of variants) {
      const hash = crypto
        .createHash('sha256')
        .update(buffer)
        .update(`${recipe}:${variant.width}:${variant.quality}`)
        .digest('hex')
        .slice(0, 8)

      const file = `${slug}-${variant.width}.${hash}.webp`
      keep.add(file)

      if (await buildVariant(sourcePath, path.join(outputDir, file), variant.width, variant.quality)) {
        generated += 1
      }

      built.push({ file, width: variant.width })
    }

    photos.push({ variants: built })
  }

  const removed = await pruneStaleFiles(keep)
  const manifest = renderManifest(photos)
  const previous = (await exists(manifestPath)) ? await fs.readFile(manifestPath, 'utf8') : null

  if (previous !== manifest) {
    await fs.writeFile(manifestPath, manifest, 'utf8')
  }

  console.log(
    `gallery: ${photos.length} photos, ${generated} thumbnails generated, ${removed.length} stale files removed`
  )
}

main().catch(error => {
  console.error(`gallery thumbnail generation failed: ${error.message}`)
  process.exitCode = 1
})
